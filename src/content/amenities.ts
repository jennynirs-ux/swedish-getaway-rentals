// Hosts' older lists don't always match the case ("Rowing boat", "Lake view")
const byLowerCase = (labels: Record<string, string>) =>
  new Map(Object.entries(labels).map(([name, label]) => [name.trim().toLowerCase(), label]));

const AMENITY_LABELS: Record<Exclude<Lang, "en">, Map<string, string>> = {
  sv: byLowerCase(AMENITY_LABELS_SV),
  de: byLowerCase(AMENITY_LABELS_DE),
};

/**
 * An amenity's label in a language, when it is one we have a label for
 * (English: none, the names are English). Otherwise show the listing's
 * translation of the name: translatedName(translation, "amenity:" + name, name).
 */
export function amenityLabel(name: string, lang: Lang): string | undefined {
  return lang === "en" ? undefined : AMENITY_LABELS[lang].get(name.trim().toLowerCase());
}
